import { readdirSync, readFileSync } from 'node:fs';
import { join } from 'node:path';

export function* jsonl(path: string): Generator<any> {
  let text: string;
  try {
    text = readFileSync(path, 'utf8');
  } catch {
    return;
  }
  for (const line of text.split('\n')) {
    if (!line.trim()) continue;
    try {
      yield JSON.parse(line);
    } catch {
      // partially-written trailing line while the agent is still running
    }
  }
}

/** Recursively lists `*.jsonl` files up to `maxDepth` levels below `dir`. */
export function findJsonl(dir: string, maxDepth: number): string[] {
  const out: string[] = [];
  const walk = (d: string, depth: number) => {
    let entries;
    try {
      entries = readdirSync(d, { withFileTypes: true });
    } catch {
      return;
    }
    for (const e of entries) {
      const p = join(d, e.name);
      if (e.isDirectory() && depth < maxDepth) walk(p, depth + 1);
      else if (e.isFile() && e.name.endsWith('.jsonl')) out.push(p);
    }
  };
  walk(dir, 1);
  return out.sort();
}

const NOISE = [
  /^\s*\[Request interrupted by user[^\]]*\]\s*$/,
  /^\s*<(local-command-stdout|local-command-stderr|task-notification|bash-stdout|bash-stderr)/,
  /^\s*Caveat: The messages below were generated by the user while running local commands/,
];

/** Slash commands that manage the CLI itself rather than asking for work. */
const HOUSEKEEPING = /^\/(clear|compact|exit|quit|model|config|cost|status|login|logout|resume|help|effort|fast|theme|vim|doctor|usage|context|memory|permissions|hooks|mcp|agents|plugin|ide|terminal-setup|release-notes|upgrade|bug|feedback)\b\s*$/i;

/** Strips harness wrappers from a user prompt; returns '' when it isn't a real prompt. */
export function cleanPrompt(raw: string): string {
  let t = raw.replace(/<system-reminder>[\s\S]*?<\/system-reminder>/g, '');
  const cmd = t.match(/<command-name>([^<]*)<\/command-name>/);
  if (cmd) {
    const args = t.match(/<command-args>([\s\S]*?)<\/command-args>/);
    t = `${cmd[1].trim()} ${(args?.[1] ?? '').trim()}`.trim();
  }
  t = t.replace(/<\/?(command-message|command-args|command-name)>/g, '').trim();
  if (!t || NOISE.some((re) => re.test(t)) || HOUSEKEEPING.test(t)) return '';
  return t;
}

export function textOf(content: unknown, blockTypes = ['text', 'input_text', 'Text']): string {
  if (typeof content === 'string') return content;
  if (!Array.isArray(content)) return '';
  return content
    .filter((b) => b && blockTypes.includes(b.type) && typeof b.text === 'string')
    .map((b) => b.text)
    .join('\n');
}

export const firstLine = (s: string, n = 70) => {
  const l = (s.split('\n').find((x) => x.trim()) ?? '').replace(/\s+/g, ' ').trim();
  return l.length > n ? l.slice(0, n - 1).trimEnd() + '…' : l;
};
